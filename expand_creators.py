def generate_svg_avatar(name: str, handle: str, accent: str) -> str:
    initial = name.strip()[0] if name else "ی"
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" width="160" height="160">
  <defs>
    <linearGradient id="grad_{handle}" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="{accent}" stop-opacity="0.85"/>
      <stop offset="100%" stop-color="#0f172a" stop-opacity="1"/>
    </linearGradient>
  </defs>
  <rect width="160" height="160" rx="36" fill="url(#grad_{handle})"/>
  <circle cx="80" cy="80" r="54" fill="none" stroke="{accent}" stroke-width="2.5" stroke-opacity="0.3"/>
  <text x="80" y="98" font-family="Vazirmatn, Tahoma, sans-serif" font-size="52" font-weight="800" fill="#ffffff" text-anchor="middle" dominant-baseline="middle">{initial}</text>
</svg>'''

def main():
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        existing = json.load(f)

    existing_handles = {x["handle"].lower() for x in existing}
    added_count = 0

    for item in NEW_CREATORS:
        name, handle, cat, subs, subs_disp, bio, tags, accent = item
        if handle.lower() in existing_handles:
            continue

        svg_filename = f"{handle.lower()}.svg"
        svg_path = AVATARS_DIR / svg_filename
        if not svg_path.exists():
            svg_content = generate_svg_avatar(name, handle, accent)
            svg_path.write_text(svg_content, encoding="utf-8")

        new_entry = {
            "name": name,
            "handle": handle,
            "channel_url": f"https://www.youtube.com/@{handle}",
            "category": cat,
            "category_title": CATEGORIES.get(cat, cat),
            "subscribers": subs,
            "subscribers_display": subs_disp,
            "bio": bio,
            "avatar": f"avatars/{svg_filename}",
            "tags": tags,
            "accent_color": accent,
            "verified": True
        }
        existing.append(new_entry)
        existing_handles.add(handle.lower())
        added_count += 1

    # Sort all by subscribers descending
    existing.sort(key=lambda x: x.get("subscribers", 0), reverse=True)

    # Re-assign sequential rank/numbering
    for idx, c in enumerate(existing, 1):
        c["id"] = idx
        c["rank"] = idx

    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    print(f"Added {added_count} new creators. Total creators now: {len(existing)}")

if __name__ == "__main__":
    main()
